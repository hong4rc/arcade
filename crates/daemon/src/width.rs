/// How many columns a character takes in a pane: 0 for a mark that joins the cell before it, 2
/// for a wide character, 1 for the rest.
pub fn char_width(c: char) -> usize {
    let n = c as u32;
    match NOT_ONE.binary_search_by(|&(first, last, _)| {
        if n < first {
            std::cmp::Ordering::Greater
        } else if n > last {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        Ok(i) => usize::from(NOT_ONE[i].2),
        Err(_) => 1,
    }
}

